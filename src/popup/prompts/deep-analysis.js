export function deepAnalysisMessages(job) {
  // Prompt 保持整段文本，方便产品侧直接编辑；外层 messages 只适配 Chat Completions API。
  const prompt = `
**角色**

你是一位资深 HR 招聘专家，需要从招聘方和业务方视角分析输入的 JD。

输入：

JD：${job.description}

公司：${job.company || "未识别"}

岗位：${job.title || "未识别"}

地点：${job.location || "未识别"}

薪资：${job.salary || "未识别"}

经验：${job.experience || "未识别"}

学历：${job.education || "未识别"}

**任务**

你的目标不是总结 JD，而是判断：

- 这个岗位真正要解决什么问题
- 招聘方实际会用什么标准筛选候选人
- 哪些能力最影响候选人的竞争力
- JD 没有直接写出，但可以合理推导出的要求

**筛选原则**

只保留会明显影响录用决策或候选人判断的信息。

删除：

- 大多数同类岗位都会出现的通用要求
- 重复观点
- 仅对 JD 原文进行改写的信息
- 缺乏足够依据的推测

如果某项通用要求在该 JD 中被明显强调，或与岗位特点强相关，可以保留。

**推理原则**

允许结合 JD 中多个信息信号进行合理推断。

隐形要求必须满足：

- JD 没有直接写明
- 有明确的信息依据支持
- 对判断候选人是否适合该岗位有实际价值

证据不足时不要输出。

**输出**

### **岗位本质**

说明这个岗位本质上要解决什么问题。

### **核心要求**

按对录用决策的影响从高到低输出。

### **隐形要求**

格式：
结论｜判断依据

### **理想候选人**

用一句话描述最适合这个岗位的人。

**输出要求**

结论优先，不展开分析过程。

数量由 JD 实际信息决定，不强制凑满固定条数。

整体保持短小精悍，通常控制在 300～500 字。

**插件输出格式要求**

为了便于插件解析，请不要输出 Markdown、代码块或额外说明，只输出严格 JSON。

JSON 字段必须是：
- essence：岗位本质，字符串数组
- coreRequirements：核心要求，字符串数组，按对录用决策的影响从高到低
- hiddenRequirements：隐形要求，字符串数组，每条格式为“结论｜判断依据”，证据不足可以为空数组
- idealCandidate：理想候选人，字符串数组，只包含一句话

输出 JSON 示例：
{
  "essence": ["岗位本质"],
  "coreRequirements": ["核心要求，按对录用决策的影响从高到低输出"],
  "hiddenRequirements": ["结论｜判断依据"],
  "idealCandidate": ["一句话描述最适合这个岗位的人"]
}
`.trim();

  return [
    {
      role: "system",
      content: "你需要严格遵守用户提供的完整提示词，只输出可解析 JSON。"
    },
    {
      role: "user",
      content: prompt
    }
  ];
}
