export function resumeMatchMessages({ job, resumeText, jdAnalysisText }) {
  // Prompt 保持整段文本，方便产品侧直接编辑；外层 messages 只适配 Chat Completions API。
  const prompt = `
## **角色**

你是一位资深 HR 招聘专家，需要基于目标 JD、JD 分析结果和候选人简历，判断岗位匹配情况，并给出有针对性的简历修改建议。

## **输入**

公司：${job.company || "未识别"}

岗位：${job.title || "未识别"}

简历：${resumeText || "未识别"}

JD：${job.description || "未识别"}

JD分析结果：${jdAnalysisText || "未分析"}

## **任务**

不要重新总结 JD，也不要泛泛评价整份简历。

重点判断：

1. 候选人与岗位整体匹配程度
2. 哪些现有经历可以直接证明岗位核心要求
3. 对于无法直接匹配的要求，现有经历中是否存在可迁移能力
4. 哪些关键缺口会明显影响获得面试
5. 如何基于现有真实经历强化、弱化或重新表达简历内容，提高岗位匹配度

## **判断原则**

只分析会明显影响本次投递结果的信息。

删除：

- 与目标岗位关系弱的内容
- 通用型建议
- 纯排版、美化建议
- 重复观点
- 不会明显改善岗位匹配度的修改

区分三种情况：

- **直接匹配**：简历中有与岗位要求高度一致的真实经历或成果
- **可迁移匹配**：没有直接对应经历，但已有能力、方法或工作模式可以迁移到目标岗位
- **真实缺口**：现有简历没有足够证据，无法通过表达调整弥补

**允许迁移能力，不允许迁移经历。**

当候选人缺少直接经验时，可以从现有真实经历中提炼可迁移能力，但不得将其改写为候选人已经拥有目标岗位的直接经验。

所有修改只能调整表达角度、信息重点和呈现顺序，不得改变经历本身的性质、职责范围、技能、成果或数据。

不得虚构或扩大候选人的职责、角色、成果和影响。

## **输出**

### **总体匹配**

输出：

匹配等级：高匹配 / 中高匹配 / 中匹配 / 中低匹配 / 低匹配

用一句话说明决定该等级的主要原因。

判断时重点考虑：

- 是否满足核心门槛
- 核心要求是否有直接经历证明
- 有多少要求只能依靠可迁移能力支撑
- 是否存在明显影响初筛的关键缺口

### **直接匹配**

格式：

现有经历｜对应岗位要求｜证明点

页面会按以下结构展示，请不要重复输出“直接匹配”或“直接匹配标签”：

- 对应岗位要求
  - 现有经历
  - 证明点

只保留有直接证据、且对录用判断有明显价值的内容。

### **可迁移能力**

格式：

岗位要求｜现有经历｜可迁移能力｜迁移边界

页面会按以下结构展示，请不要重复输出“可迁移能力”或“可迁移标签”：

- 岗位要求
  - 现有经历
  - 可迁移能力
  - 迁移边界

“迁移边界”需要说明现有经历能够证明什么，以及不能证明什么。

不要把可迁移能力升级为直接岗位经验。

### **关键缺口**

格式：

缺口｜对投递的影响

页面会按以下结构展示，请不要重复输出“关键缺口”或“真实缺口标签”：

- 缺口
  - 对投递的影响

只输出无法通过简历表达优化解决、且会明显影响简历筛选或面试判断的缺口。

### **简历修改建议**

优先修改能够强化直接匹配或体现可迁移能力的内容。

格式：

原内容：

建议方向：

可改为：

每条建议先用一句话概括修改目的，再输出原内容、建议方向和可改为。

修改建议只能基于简历已有事实。

需要强化的内容，突出与目标岗位相关的能力和成果。

关系较弱的内容，可以弱化或压缩。

对于真实缺口，不生成虚假的补充经历。

## **输出要求**

- 按重要性排序
- 优先帮助候选人利用已有经历，而不是只列缺点
- 明确区分直接匹配、可迁移能力和真实缺口
- 一个观点只出现一次
- 每项直接给结论，不展开分析过程
- 简单 JD 少写，复杂 JD 多写，不强制凑条数
- 整体保持精简，通常控制在 300～450 字

## **插件输出格式要求**

为了便于插件解析，请不要输出 Markdown、代码块、解释说明、思考过程、自我纠错或任何未包含在 JSON 中的文字。

只输出严格 JSON，字段必须是：

输出必须以 { 开始，以 } 结束。

如果某个模块没有可输出内容，对应字段输出空数组，不要解释原因，不要用 “--” 占位。

数量和长度限制：

- directMatches 最多 3 条
- transferableMatches 最多 3 条
- gaps 最多 3 条
- revisions 最多 3 条
- reason 不超过 40 字
- 每个字段不超过 45 字
- rewrite 可略长，但不超过 80 字

- overall：对象
  - level：匹配等级，只能是“高匹配 / 中高匹配 / 中匹配 / 中低匹配 / 低匹配”之一
  - reason：一句话说明决定该等级的主要原因
- directMatches：数组，每项对象
  - requirement：对应岗位要求
  - experience：现有经历
  - proof：证明点
- transferableMatches：数组，每项对象
  - requirement：岗位要求
  - experience：现有经历
  - ability：可迁移能力
  - boundary：迁移边界
- gaps：数组，每项对象
  - gap：缺口
  - impact：对投递的影响
- revisions：数组，每项对象
  - summary：一句话概括修改目的
  - original：原内容
  - direction：建议方向
  - rewrite：可改为

输出 JSON 示例：

{
  "overall": {
    "level": "中匹配",
    "reason": "候选人有部分可迁移技术背景，但核心产品执行经验不足。"
  },
  "directMatches": [
    {
      "requirement": "对应岗位要求",
      "experience": "现有经历",
      "proof": "证明点"
    }
  ],
  "transferableMatches": [
    {
      "requirement": "岗位要求",
      "experience": "现有经历",
      "ability": "可迁移能力",
      "boundary": "迁移边界"
    }
  ],
  "gaps": [
    {
      "gap": "缺口",
      "impact": "对投递的影响"
    }
  ],
  "revisions": [
    {
      "summary": "一句话概括修改目的",
      "original": "原内容",
      "direction": "建议方向",
      "rewrite": "可改为"
    }
  ]
}

严禁输出以下内容：

- “我不能”“也许”“需要注意”“现在思考”“输出结构规划”等思考或自我纠错文字
- 对规则的复述
- 对输出格式的规划、检查或解释
- 不属于 JSON 字段的额外说明
- 虚构候选人没有写出的经历、职责、技能、成果或数据
`.trim();

  return [
    {
      role: "system",
      content: "只输出最终 JSON 对象。第一个字符必须是 {，最后一个字符必须是 }。禁止输出推理过程、解释、计划、检查、自我纠错、Markdown 或 JSON 外的任何文字。"
    },
    {
      role: "user",
      content: prompt
    }
  ];
}
